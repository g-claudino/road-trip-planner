export function getVisaRequirement(
  nationalityCode: string,
  countryCode: string,
): { entry: VisaEntry; isProxy: boolean } | null {
  if (nationalityCode === countryCode) return null;

  const row = VISA_MATRIX[countryCode];
  if (!row) return null;

  const proxyCode = NATIONALITY_PROXY[nationalityCode];
  const lookupCode = proxyCode ?? nationalityCode;
  const entry = row[lookupCode];
  if (!entry) return null;

  return { entry, isProxy: !!proxyCode };
}

export function nationalityName(code: string): string {
  return NATIONALITIES.find((n) => n.code === code)?.name ?? code;
}
